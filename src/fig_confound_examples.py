"""Qualitative 4-panel illustration of in-focus, lens defocus, motion blur, and fog.

Draws results/figures/fig_confound_examples.{pdf,png} from
results/figures/data/confound_examples.npz (generated by src/fig_confound_examples_data.py).
Top row: 320x320 px RobotCar crop with dashed ROI box; bottom row: 3.3x zoom of the 96x96 px ROI.
"""
import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.patches as patches
import matplotlib.pyplot as plt
import numpy as np

R = Path(__file__).resolve().parents[1] / "results"
plt.rcParams.update({
    "font.family": "STIXGeneral",
    "mathtext.fontset": "stix",
    "font.size": 8,
    "pdf.fonttype": 42,
    "savefig.dpi": 300,
})

# Street-name sign and brick wall 96x96 ROI within the 320x320 crop
ZOOM_Y0, ZOOM_X0, ZOOM_SZ = 88, 120, 96


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=R / "figures")
    a = ap.parse_args()

    d = np.load(R / "figures/data/confound_examples.npz")
    m = json.loads(str(d["meta"]))
    panels = [
        ("crop_focus", "(a)", "In focus\n" + r"($\Delta z = 0$)"),
        ("crop_defocus", "(b)", "Lens defocus\n" + r"($\Delta z = +0.91\,\delta$)"),
        ("crop_motion", "(c)", f"Motion blur\n({m['motion_len_px']:.2f} px, {m['motion_angle_deg']:.0f}" + r"$^\circ$)"),
        ("crop_fog", "(d)", f"Fog\n" + r"($t = " + f"{m['fog_transmission']:.3f}" + r"$, $A = 220$)"),
    ]

    fig, axes = plt.subplots(2, 4, figsize=(7.16, 3.65),
                             gridspec_kw={"height_ratios": [1.0, 0.72]})
    fig.subplots_adjust(left=0.008, right=0.992, top=0.89, bottom=0.08, wspace=0.04, hspace=0.05)

    for col, (key, tag, title) in enumerate(panels):
        img = d[key]
        ax_top = axes[0, col]
        ax_top.imshow(img, interpolation="nearest")
        rect = patches.Rectangle((ZOOM_X0, ZOOM_Y0), ZOOM_SZ, ZOOM_SZ,
                                 linewidth=0.8, edgecolor="white", linestyle="--", facecolor="none")
        ax_top.add_patch(rect)
        ax_top.set_xticks([])
        ax_top.set_yticks([])
        ax_top.set_title(title, fontsize=8, pad=4, linespacing=1.15)

        ax_bot = axes[1, col]
        zoom = img[ZOOM_Y0:ZOOM_Y0 + ZOOM_SZ, ZOOM_X0:ZOOM_X0 + ZOOM_SZ]
        ax_bot.imshow(zoom, interpolation="nearest")
        ax_bot.set_xticks([])
        ax_bot.set_yticks([])
        ax_bot.set_xlabel(tag, fontsize=8, labelpad=4)

    a.out.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(a.out / f"fig_confound_examples.{ext}")
    print(f"Wrote {a.out / 'fig_confound_examples.pdf'} ({m['traversal']}/{m['frame']})")


if __name__ == "__main__":
    main()
